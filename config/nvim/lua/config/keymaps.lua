-- ========== Neovim 快捷键映射 ==========
-- 从 ~/.vimrc 转换为 Lua 格式

local map = vim.keymap.set
-- 让 <Space> 只作为 Leader 前缀，不执行默认右移
map({ "n", "v", "o" }, "<Space>", "<Nop>", { silent = true })

-- ========== Leader 键 ==========
vim.g.mapleader = " "

-- ========== 基础操作 ==========
-- 快速保存
map('n', '<Leader>w', ':w<CR>', { desc = "保存文件" })

-- 快速退出
map('n', '<Leader>q', ':q<CR>', { desc = "退出" })

-- 手动唤起 which-key（兜底）
-- 注意：不要在这里直接调用 wk.show()，避免递归触发
map('n', '<Leader>?', '<cmd>WhichKey <leader><CR>', { desc = "显示快捷键帮助" })

-- ========== 搜索相关 ==========
-- 取消搜索高亮
map('n', '<C-n>', ':noh<CR>', { desc = "取消搜索高亮" })

-- ========== 快速移动 ==========
-- J/K 快速移动 5 行
map('n', 'J', '5j', { desc = "向下移动 5 行" })
map('n', 'K', '5k', { desc = "向上移动 5 行" })

-- 合并行功能改用 空格+j
map('n', '<Leader>j', 'J', { desc = "合并当前行和下一行" })

-- 快速移动到行首/行尾
map('n', 'H', '^', { desc = "移动到行首（非空白字符）" })
map('n', 'L', '$', { desc = "移动到行尾" })

-- ========== 分屏导航 ==========
-- 在分屏间快速移动
map('n', '<C-h>', '<C-w>h', { desc = "移动到左侧窗口" })
map('n', '<C-j>', '<C-w>j', { desc = "移动到下方窗口" })
map('n', '<C-k>', '<C-w>k', { desc = "移动到上方窗口" })
map('n', '<C-l>', '<C-w>l', { desc = "移动到右侧窗口" })

-- ========== 调整分屏大小 ==========
map('n', '<Leader>=', '<C-w>=', { desc = "均分所有窗口" })
map('n', '<Leader>-', '<C-w>-', { desc = "减小窗口高度" })
map('n', '<Leader>+', '<C-w>+', { desc = "增大窗口高度" })

-- ========== 复制增强 ==========
-- Y 复制到行尾（更符合 D/C 的逻辑）
map('n', 'Y', 'y$', { desc = "复制到行尾" })

-- ========== 可视模式 ==========
-- 在可视模式下保持选中状态缩进
map('v', '<', '<gv', { desc = "左缩进并保持选中" })
map('v', '>', '>gv', { desc = "右缩进并保持选中" })

-- 移动选中的行
map('v', 'J', ":m '>+1<CR>gv=gv", { desc = "向下移动选中行" })
map('v', 'K', ":m '<-2<CR>gv=gv", { desc = "向上移动选中行" })
